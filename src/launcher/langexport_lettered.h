/* where a release has them: a level's picture (its number in the level file's picture list), its size and fingerprint.
 * A translation that re-lettered a picture in place (the Portuguese one) changed its fingerprint, not its place. */
struct LetteredPlace {
    u16 picture, w, h;
    u64 fingerprint;
};

/* a release's level: its folder's name as the release has it, the number of pictures its level file lists, and its
 * lettered pictures' places (`count` of them in kLetteredPlaces, from `first`) */
struct LetteredLevel {
    const char *release, *level;
    u16 pictures, first, count;
};


