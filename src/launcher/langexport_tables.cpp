static const char *const s_strings[7][EXPORT_REWOOLED_MENU_COUNT] = {
    EXPORT_REWOOLED_MENU_ENGLISH, /* English */
    EXPORT_REWOOLED_MENU_ENGLISH, /* French: to translate */
    EXPORT_REWOOLED_MENU_ENGLISH, /* German: to translate */
    EXPORT_REWOOLED_MENU_ENGLISH, /* Dutch: to translate */
    EXPORT_REWOOLED_MENU_ENGLISH, /* Spanish: to translate */
    EXPORT_REWOOLED_MENU_ENGLISH, /* Italian: to translate */
    EXPORT_REWOOLED_MENU_ENGLISH, /* Portuguese (Brazil): to translate */
};

const char *ExportTables_RewooledMenuString(unsigned langMask, unsigned index)
{
    for (unsigned bit = 0; bit < 7; bit++)
        if (langMask == (1u << bit))
            return index >= 1 && index <= EXPORT_REWOOLED_MENU_COUNT ? s_strings[bit][index - 1] : 0;
    return 0;
}
